package memory

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"

	"github.com/yangflow/hoplet/internal/store"
)

const profileFile = "PROFILE.md"

// writeProfile regenerates the digest of active entries.
func (s *Service) writeProfile(ctx context.Context) error {
	rows, err := s.store.SearchMemoryIndex(ctx, store.MemoryQuery{Status: string(StatusActive)})
	if err != nil {
		return err
	}
	var b bytes.Buffer
	b.WriteString("<!-- Generated by Hoplet from entries/. Edits here are overwritten. -->\n# Profile\n")
	for _, c := range []Category{CategoryFact, CategoryPreference, CategoryConvention, CategoryExperience} {
		wrote := false
		for _, r := range rows {
			if r.Category != string(c) {
				continue
			}
			if !wrote {
				fmt.Fprintf(&b, "\n## %s\n\n", c)
				wrote = true
			}
			fmt.Fprintf(&b, "- %s %s\n", r.ID, r.Title)
		}
	}
	f, err := os.CreateTemp(s.root, tempPrefix+"*")
	if err != nil {
		return fmt.Errorf("memory: create profile: %w", err)
	}
	_, err = f.Write(b.Bytes())
	err = errors.Join(err, f.Close())
	if err == nil {
		err = os.Rename(f.Name(), filepath.Join(s.root, profileFile))
	}
	if err != nil {
		return errors.Join(fmt.Errorf("memory: write profile: %w", err), os.Remove(f.Name()))
	}
	return nil
}
