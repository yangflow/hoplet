/** `text` as one inline code span, on one line, fenced past any backticks inside it. */
export function code(text: string): string {
  const one = text.replace(/\s*[\r\n]+\s*/g, ' ');
  if (one === '') return '';
  const longest = Math.max(0, ...(one.match(/`+/g) ?? []).map((r) => r.length));
  const fence = '`'.repeat(longest + 1);
  const pad = one.startsWith('`') || one.endsWith('`') ? ' ' : '';
  return `${fence}${pad}${one}${pad}${fence}`;
}

/** `text` as a fenced block whose fence no line inside it can close, each line indented by `indent`. */
export function fenced(text: string, lang = '', indent = ''): string {
  const longest = Math.max(0, ...(text.match(/`+/g) ?? []).map((r) => r.length));
  const fence = '`'.repeat(Math.max(3, longest + 1));
  const body = text.replace(/\r\n/g, '\n').replace(/\n+$/, '');
  return [`${fence}${lang}`, ...body.split('\n'), fence].map((l) => `${indent}${l}`).join('\n');
}

/** A table cell: a pipe would end it. */
function cell(text: string): string {
  return text.replace(/\|/g, '\\|');
}

/** Every line of `text` quoted. */
function quote(text: string): string {
  return text
    .split('\n')
    .map((l) => (l.trim() === '' ? '>' : `> ${l}`))
    .join('\n');
}

export function sizeText(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} KiB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MiB`;
}

export function durationText(ms: number): string {
  const minutes = Math.round(ms / 60_000);
  if (minutes < 1) return `${Math.max(0, Math.round(ms / 1000))} s`;
  if (minutes < 60) return `${minutes} min`;
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  return m === 0 ? `${h} h` : `${h} h ${m} min`;
}

/** The clock and the calendar of a time in a time zone. */
export function timeParts(at: string | number, tz: string): { date: string; time: string } | null {
  const ms = typeof at === 'number' ? at : Date.parse(at);
  if (!Number.isFinite(ms)) return null;
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: tz,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
  }).formatToParts(new Date(ms));
  const get = (type: string) => parts.find((p) => p.type === type)?.value ?? '';
  return {
    date: `${get('year')}-${get('month')}-${get('day')}`,
    time: `${get('hour')}:${get('minute')}`,
  };
}

const VERBS: Record<ToolKind, string> = {
  read: 'Read',
  edit: 'Edited',
  write: 'Wrote',
  run: 'Ran',
  search: 'Searched',
  list: 'Listed',
  fetch: 'Fetched',
  call: 'Called',
  view: 'Viewed',
  other: 'Used',
};

/** One tool call as a list item, with its output when the file keeps it. */
export function toolLine(tool: ExportTool): string {
  const verb = VERBS[tool.kind];
  const named =
    tool.kind === 'call' || tool.kind === 'other'
      ? `${verb} ${code(tool.mcp ? `${tool.mcp.server}/${tool.mcp.tool}` : tool.name)}${tool.arg ? ` ${code(tool.arg)}` : ''}`
      : `${verb} ${tool.arg ? code(tool.arg) : code(tool.name)}`;
  const r = tool.result;
  let status = '';
  if (r && tool.kind === 'run') status = r.exit !== null ? ` · exit ${r.exit}` : ' · failed';
  else if (r?.isError) status = ' · failed';
  const lines = [`- ${named}${status}`];
  if (r && (tool.kind === 'run' || r.isError) && r.bytes > 0) {
    if (r.text !== undefined && r.text.trim() !== '') lines.push('', fenced(r.text, 'text', '  '));
    else if (r.text === undefined) {
      lines.push(`- Output elided: ${sizeText(r.bytes)}, see the session in Hoplet`);
    }
  }
  return lines.join('\n');
}

export interface TurnHeading {
  machine?: string;
  /** When the turn started, in the export's time zone. */
  time?: string;
}

/** One turn of the conversation section. `replies` keeps the user's messages and the turn's last reply. */
export function renderTurn(
  turn: ExportTurn,
  mode: Exclude<ExportConversation, 'none'>,
  heading: TurnHeading,
): string {
  const head = [`Turn ${turn.n}`, heading.machine, heading.time].filter(Boolean).join(' · ');
  const out: string[] = [`### ${head}`, ''];
  if (turn.prompt !== null) out.push(quote(`**You:** ${turn.prompt}`), '');
  if (mode === 'replies') {
    const last = [...turn.items].reverse().find((i) => i.type === 'text');
    if (last?.type === 'text') out.push(last.text, '');
    return `${out.join('\n')}\n`;
  }
  for (const item of turn.items) {
    if (item.type === 'text') out.push(item.text, '');
    else if (item.type === 'steer') out.push(quote(`**You, during the turn:** ${item.text}`), '');
    else if (item.type === 'image') out.push(`*An image (${item.mediaType}).*`, '');
    else {
      const n = item.tools.length;
      out.push(
        `<details><summary>${n} tool ${n === 1 ? 'call' : 'calls'}</summary>`,
        '',
        ...item.tools.map(toolLine),
        '',
        '</details>',
        '',
      );
    }
  }
  return `${out.join('\n')}\n`;
}

/** The line between two turns where the session moved to another machine. */
export function renderHandoff(from: string, to: string, turn: number, time?: string): string {
  return `---\n\n*Handed off from ${from} to ${to} at turn ${turn}${time ? ` · ${time}` : ''}.*\n\n`;
}

export interface ExportHeader {
  title: string;
  sessionId: string;
  project: string;
  branch?: string;
  provider: string;
  /** The machines in the order the session ran on them; absent without the machines option. */
  machines?: string[];
  /** `MacBook Pro (turns 1–8) → studio (turns 9–12)` */
  machineRow?: string;
  /** `turn 9, 2026-10-24 14:20` for each hand-off. */
  handoffRows?: string[];
  turns: number;
  /** How long the session ran, first line to last. */
  durationMs?: number;
  /** The net diff's totals, when the changes were read. */
  diff?: { files: number; added: number; removed: number };
  exported: string;
  version: string;
  summary?: string;
  conversation: ExportConversation;
}

function yaml(value: string): string {
  return JSON.stringify(value);
}

/** The front matter, title, review warning, metadata table, summary, and the conversation heading. */
export function renderHeader(h: ExportHeader): string {
  const front = [
    '---',
    `title: ${yaml(h.title)}`,
    `session: ${h.sessionId}`,
    `project: ${yaml(h.project)}`,
    `provider: ${h.provider}`,
    ...(h.machines ? [`machines: [${h.machines.map(yaml).join(', ')}]`] : []),
    `turns: ${h.turns}`,
    `exported: ${h.exported}`,
    `hoplet: ${h.version}`,
    '---',
  ];
  const turnsRow = [`${h.turns}`];
  if (h.durationMs !== undefined) turnsRow.push(durationText(h.durationMs));
  if (h.diff) {
    turnsRow.push(
      `+${h.diff.added} −${h.diff.removed} in ${h.diff.files} ${h.diff.files === 1 ? 'file' : 'files'}`,
    );
  }
  const rows = [
    `| Project | ${cell(h.project)}${h.branch ? ` · ${cell(code(h.branch))}` : ''} |`,
    ...(h.machineRow ? [`| Machines | ${cell(h.machineRow)} |`] : []),
    ...(h.handoffRows ?? []).map((r) => `| Hand-off | ${cell(r)} |`),
    `| Turns | ${turnsRow.join(' · ')} |`,
  ];
  const out = [
    ...front,
    '',
    `# ${h.title.replace(/\s*\n\s*/g, ' ')}`,
    '',
    '> **Check before sharing.** Hoplet masked the values that look like credentials,',
    '> shown as `[redacted:<kind>]`. Other secrets may remain in the text.',
    '',
    '| | |',
    '|---|---|',
    ...rows,
    '',
  ];
  if (h.summary !== undefined && h.summary.trim() !== '') {
    out.push('## Summary', '', h.summary.trim().replace(/\r\n/g, '\n'), '');
  }
  if (h.conversation !== 'none') out.push('## Conversation', '');
  return `${out.join('\n')}\n`;
}

export type ExportCommand = {
  turn: number;
  machine?: string;
  command: string;
  exit: number | null;
};

/** The commands each turn ran, in order. */
export function commandsOf(turn: ExportTurn, machine?: string): ExportCommand[] {
  const out: ExportCommand[] = [];
  for (const item of turn.items) {
    if (item.type !== 'tools') continue;
    for (const tool of item.tools) {
      if (tool.kind !== 'run' || tool.arg === '') continue;
      out.push({
        turn: turn.n,
        ...(machine ? { machine } : {}),
        command: tool.arg,
        exit: tool.result ? tool.result.exit : null,
      });
    }
  }
  return out;
}

/** The commands table; `more` counts the commands past EXPORT_MAX_COMMANDS. */
export function renderCommands(commands: ExportCommand[], more: number, machines: boolean): string {
  const out = ['## Commands', ''];
  if (commands.length === 0) out.push('*No commands were run.*', '');
  else {
    out.push(
      machines ? '| Turn | Machine | Command | Exit |' : '| Turn | Command | Exit |',
      machines ? '|---|---|---|---|' : '|---|---|---|',
    );
    for (const c of commands) {
      const exit = c.exit === null ? '—' : String(c.exit);
      const cells = [String(c.turn), ...(machines ? [cell(c.machine ?? '')] : [])];
      out.push(`| ${[...cells, cell(code(c.command)), exit].join(' | ')} |`);
    }
    out.push('');
    if (more > 0)
      out.push(`*${more} more ${more === 1 ? 'command is' : 'commands are'} not listed.*`, '');
  }
  return `${out.join('\n')}\n`;
}

/** The header lines of one file's diff. */
export function diffFileHeader(path: string, status: string): string {
  const from = status === 'added' || status === 'untracked' ? '/dev/null' : `a/${path}`;
  const to = status === 'deleted' ? '/dev/null' : `b/${path}`;
  return `--- ${from}\n+++ ${to}\n`;
}
