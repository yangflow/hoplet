/**
 * The Markdown of a session export (ADR 0040): turns built from conversation entries one at a time, and the text
 * of each part of the file. Pure: session-export.ts reads the session, masks and streams what this writes.
 */
import type { Entry, ExportConversation, ToolKind, ToolMcp } from '@hoplet/shared';
import { ELIDE_ABOVE_BYTES } from './projection/index.ts';

/** A tool output at most this long is written in the file; a longer one is named with its size. */
export const EXPORT_OUTPUT_MAX_BYTES = ELIDE_ABOVE_BYTES;

/** The most rows of the commands table. */
export const EXPORT_MAX_COMMANDS = 1000;

/** The longest command the commands table writes; a longer one is cut with an ellipsis. */
const COMMAND_MAX_CHARS = 200;

export type ExportResult = {
  isError: boolean;
  /** The exit code of a command: from `Exit code N`, 0 for a result without an error, else null. */
  exit: number | null;
  bytes: number;
  /** The output, kept for a command or a failure no longer than EXPORT_OUTPUT_MAX_BYTES. */
  text?: string;
};

export type ExportTool = {
  id: string;
  kind: ToolKind;
  name: string;
  mcp?: ToolMcp;
  arg: string;
  result?: ExportResult;
};

export type ExportItem =
  | { type: 'text'; text: string }
  | { type: 'steer'; text: string }
  | { type: 'image'; mediaType: string }
  | { type: 'tools'; tools: ExportTool[] };

export type ExportTurn = {
  /** From 1, in the order of the session. */
  n: number;
  /** When the turn's first and last lines were written (ISO 8601), when the vendor recorded it. */
  ts?: string;
  lastTs?: string;
  /** The user's message that started the turn; null for lines before the first message. */
  prompt: string | null;
  items: ExportItem[];
};

const META_TEXT =
  /^\s*<(command-name|command-message|command-args|local-command-stdout|local-command-caveat|system-reminder|user-prompt-submit-hook|bash-input|bash-stdout|bash-stderr)\b|^\s*Caveat: The messages below were generated by the user while running local commands/;

/** The `/name args` a user line ran, from Claude Code's tags or as the user typed it. */
function commandOf(text: string): string | null {
  const tag = /<command-name>\s*\/?([^<\s]+)\s*<\/command-name>/.exec(text);
  if (tag) {
    const args = /<command-args>([\s\S]*?)<\/command-args>/.exec(text)?.[1]?.trim() ?? '';
    return `/${tag[1]}${args ? ` ${args}` : ''}`;
  }
  return null;
}

/** A user line that starts a turn: its first text that is the user's own, and the block it is. */
function promptOf(entry: Entry): { text: string; index: number } | null {
  if (entry.role !== 'user') return null;
  for (const [index, block] of entry.blocks.entries()) {
    if ('elided' in block || block.type !== 'text' || block.text.trim() === '') continue;
    const command = /^\s*<command-name>/.test(block.text) ? commandOf(block.text) : null;
    if (command) return { text: command, index };
    if (!META_TEXT.test(block.text)) return { text: block.text.trim(), index };
  }
  return null;
}

function firstLine(text: string, max: number): string {
  const line = text.trim().split('\n')[0] ?? '';
  return line.length > max ? `${line.slice(0, max)}…` : line;
}

function relativePath(path: string, cwd: string): string {
  const base = cwd.replace(/[/\\]+$/, '');
  return base && path.startsWith(`${base}/`) ? path.slice(base.length + 1) : path;
}

/** What a tool call names: its file, command, pattern or query, on one line. */
export function toolArg(input: unknown, cwd: string): string {
  if (!input || typeof input !== 'object') return '';
  const rec = input as Record<string, unknown>;
  for (const k of ['file_path', 'path', 'target_file', 'notebook_path']) {
    const v = rec[k];
    if (typeof v === 'string' && v.trim()) return relativePath(v.trim(), cwd);
  }
  for (const k of ['command', 'pattern', 'query', 'url', 'description', 'prompt', 'skill']) {
    const v = rec[k];
    if (typeof v === 'string' && v.trim()) return firstLine(v, COMMAND_MAX_CHARS);
    if (k === 'command' && Array.isArray(v) && v.every((p) => typeof p === 'string')) {
      return firstLine(v.join(' '), COMMAND_MAX_CHARS);
    }
  }
  return '';
}

function resultOf(kind: ToolKind, content: string, isError: boolean): ExportResult {
  const bytes = Buffer.byteLength(content);
  const code = /^Exit code (-?\d+)/.exec(content);
  const exit = code ? Number(code[1]) : isError ? null : 0;
  const keep = (kind === 'run' || isError) && bytes <= EXPORT_OUTPUT_MAX_BYTES;
  return { isError, exit, bytes, ...(keep ? { text: content } : {}) };
}

/**
 * Builds turns from entries in session order: a user's message starts a turn and what follows belongs to it.
 * `add` and `finish` return the turn that just ended. With `light` a turn carries no items: the first pass
 * only counts turns and their times.
 */
export class TurnBuilder {
  private current: ExportTurn | null = null;
  private count = 0;
  private readonly open = new Map<string, ExportTool>();

  private readonly cwd: string;
  private readonly light: boolean;

  constructor(cwd: string, light = false) {
    this.cwd = cwd;
    this.light = light;
  }

  get turns(): number {
    return this.count;
  }

  add(entry: Entry): ExportTurn | null {
    let ended: ExportTurn | null = null;
    const prompt = entry.steered && this.current ? null : promptOf(entry);
    if (prompt || !this.current) {
      ended = this.current;
      this.open.clear();
      this.current = {
        n: ++this.count,
        ...(entry.ts ? { ts: entry.ts, lastTs: entry.ts } : {}),
        prompt: prompt?.text ?? null,
        items: [],
      };
    }
    const turn = this.current;
    if (entry.ts) {
      turn.ts ??= entry.ts;
      turn.lastTs = entry.ts;
    }
    if (this.light) return ended;
    entry.blocks.forEach((block, i) => {
      if (prompt && i === prompt.index) return;
      if ('elided' in block) return;
      switch (block.type) {
        case 'text': {
          const text = block.text.trim();
          if (text === '') return;
          if (entry.role === 'assistant') turn.items.push({ type: 'text', text });
          else if (entry.role === 'user' && entry.steered && !META_TEXT.test(text)) {
            turn.items.push({ type: 'steer', text });
          }
          return;
        }
        case 'tool-call': {
          const tool: ExportTool = {
            id: block.id,
            kind: block.kind,
            name: block.name,
            ...(block.mcp ? { mcp: block.mcp } : {}),
            arg: toolArg(block.input, this.cwd),
          };
          const last = turn.items[turn.items.length - 1];
          if (last?.type === 'tools') last.tools.push(tool);
          else turn.items.push({ type: 'tools', tools: [tool] });
          this.open.set(block.id, tool);
          return;
        }
        case 'tool-result': {
          const tool = this.open.get(block.id);
          if (!tool) return;
          this.open.delete(block.id);
          tool.result = resultOf(tool.kind, block.content, block.isError === true);
          return;
        }
        case 'image':
          if (entry.role === 'user') turn.items.push({ type: 'image', mediaType: block.mediaType });
          return;
        default:
          return;
      }
    });
    return ended;
  }

  finish(): ExportTurn | null {
    const ended = this.current;
    this.current = null;
    this.open.clear();
    return ended;
  }
}

