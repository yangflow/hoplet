/**
 * Turns from conversation entries (docs/spec.md#hoplet): a user prompt starts a turn, and the assistant text,
 * thinking, tool calls, results and file edits that follow belong to it. System and meta lines attach to the
 * nearest turn; lines before the first prompt of the loaded window form a turn without a prompt.
 */
import type { BlockType, ElidedBlock, Entry, FullBlock, ToolKind, ToolMcp } from '@hoplet/shared';
import { type Language, languageOfPath } from '../../../lib/highlight.ts';
import { type DiffRow, lineDiff } from './diff.ts';
import { base64Bytes } from './tools.ts';

/** An elided block: its preview, its size, and where to fetch the whole of it. */
export type Elided = {
  bytes: number;
  preview: string;
  line: number;
  block: number;
  type: BlockType;
};

export type ToolResult = {
  key: string;
  lineNo: number;
  /** When the result line was written; with the call's, the duration of the call. */
  ts?: string;
  text: string;
  failed: boolean;
  bytes: number;
  elided?: Elided;
};

export type ToolRow = {
  kind: 'tool';
  key: string;
  lineNo: number;
  tool: string;
  toolKind: ToolKind;
  /** The vendor's ID of the call; a rule decision is joined to the call by it. */
  toolUseId?: string;
  mcp?: ToolMcp;
  /** When the call line was written. */
  ts?: string;
  /** The file a file tool names, relative to the session's directory when it lies inside it. */
  path?: string;
  arg: string;
  /** The input as the call stored it. */
  input: unknown;
  result?: ToolResult;
};

export type EditRow = {
  kind: 'edit';
  key: string;
  lineNo: number;
  tool: string;
  toolKind: ToolKind;
  /** The vendor's ID of the call; a rule decision is joined to the call by it. */
  toolUseId?: string;
  path: string;
  added: number;
  removed: number;
  rows: DiffRow[];
  more: number;
  language: Language;
  result?: ToolResult;
};

export type TextRow = { kind: 'text'; key: string; lineNo: number; text: string; elided?: Elided };
export type ThinkingRow = {
  kind: 'thinking';
  key: string;
  lineNo: number;
  text: string;
  elided?: Elided;
};
export type NoteRow = {
  kind: 'note';
  key: string;
  lineNo: number;
  family: 'result' | 'system' | 'file' | 'other';
  label: string;
  text: string;
  failed?: boolean;
  elided?: Elided;
};
/** What a local command printed (`/context`, `/compact`): `command` is the one the turn's prompt ran. */
export type CommandRow = {
  kind: 'command';
  key: string;
  lineNo: number;
  command?: string;
  text: string;
  /** `/compact` reports what it did instead of printing a table. */
  compact?: { from?: string; to?: string };
};
/** Where the conversation was compacted; `sizes` are the tokens before and after when no `/compact` block states them. */
export type BoundaryRow = {
  kind: 'boundary';
  key: string;
  lineNo: number;
  text: string;
  sizes?: { from: string; to: string };
};
/** A message the user steered into the turn: where the model took it in, at a tool gap (ADR 0020). */
export type SteerRow = {
  kind: 'steer';
  key: string;
  lineNo: number;
  text: string;
  elided?: Elided;
};
export type FoldRow = { kind: 'fold'; key: string; lineNo: number; tools: ToolRow[] };

export type Row =
  | TextRow
  | ThinkingRow
  | ToolRow
  | EditRow
  | NoteRow
  | CommandRow
  | BoundaryRow
  | SteerRow
  | FoldRow;

/** A slash command a prompt ran: its name without the slash, and what followed it. */
export type CommandCall = { name: string; args: string };

export type TurnSummary = { files: number; tools: number; durationMs: number | null };

export type Turn = {
  key: string;
  startLine: number;
  endLine: number;
  prompt: { text: string; elided?: Elided; command?: CommandCall } | null;
  ts: string | undefined;
  rows: Row[];
  summary: TurnSummary;
};

const META_TEXT =
  /^\s*<(command-name|command-message|command-args|local-command-stdout|local-command-caveat|system-reminder|user-prompt-submit-hook|bash-input|bash-stdout|bash-stderr)\b|^\s*Caveat: The messages below were generated by the user while running local commands/;

const COMMAND_TAGS =
  /^\s*<(command-name|command-message|command-args|local-command-caveat)\b|^\s*Caveat: The messages below were generated by the user while running local commands/;
const STDOUT = /^\s*<local-command-stdout>([\s\S]*?)(?:<\/local-command-stdout>)?\s*$/;

/** The command a user line ran, from Claude Code's tags or from the `/name args` the user typed. */
export function parseCommand(text: string): CommandCall | null {
  const tag = /<command-name>\s*\/?([^<\s]+)\s*<\/command-name>/.exec(text);
  if (tag) {
    const args = /<command-args>([\s\S]*?)<\/command-args>/.exec(text)?.[1] ?? '';
    return { name: tag[1] as string, args: args.trim() };
  }
  const typed = /^\/([A-Za-z][\w:.-]*)(?:\s+([\s\S]*?))?\s*$/.exec(text.trim());
  return typed ? { name: typed[1] as string, args: typed[2] ?? '' } : null;
}

// biome-ignore lint/suspicious/noControlCharactersInRegex: ESC starts the sequence
const ANSI = /\u001b\[[0-9;?]*[ -/]*[@-~]/g;

/** What a terminal would show of `text`: without the escape sequences Claude Code colours its output with. */
export function stripAnsi(text: string): string {
  return text.replace(ANSI, '');
}

/** A token count as the design writes it: 26208 is "26.2k", 840 is "840". */
export function formatTokens(n: number): string {
  return n >= 1000 ? `${(n / 1000).toFixed(1)}k` : String(Math.round(n));
}

/** The boundary block of a compaction: its words, and the sizes when the core carried `{preTokens, postTokens}`. */
export function parseBoundary(block: { text?: string | undefined; label?: string | undefined }): {
  text: string;
  sizes?: { from: string; to: string };
} {
  const raw = block.text ?? '';
  if (block.label !== undefined && raw.startsWith('{')) {
    try {
      const meta = JSON.parse(raw) as { preTokens?: unknown; postTokens?: unknown };
      if (typeof meta.preTokens === 'number' && typeof meta.postTokens === 'number') {
        return {
          text: block.label,
          sizes: { from: formatTokens(meta.preTokens), to: formatTokens(meta.postTokens) },
        };
      }
    } catch {
      // not the core's JSON: the text is what the line said
    }
  }
  return { text: block.label ?? raw };
}

function elidedOf(entry: Entry, block: ElidedBlock, index: number): Elided {
  const [line, at] = block.ref.split('/').map(Number);
  return {
    bytes: block.bytes,
    preview: block.preview,
    line: Number.isFinite(line) ? (line as number) : entry.lineNo,
    block: Number.isFinite(at) ? (at as number) : index,
    type: block.type,
  };
}

/** What an image row names: the file the URL points at, else the media type. */
function imageName(raw: { mediaType: string; url?: string | undefined }): string {
  if (!raw.url || raw.url.startsWith('data:')) return raw.mediaType;
  return raw.url.split(/[?#]/)[0]?.split('/').pop() || raw.mediaType;
}

function firstLine(text: string, max = 160): string {
  return (text.trim().split('\n')[0] ?? '').slice(0, max);
}

function relativePath(path: string, cwd: string | undefined): string {
  if (!cwd) return path;
  const base = cwd.replace(/[/\\]+$/, '');
  return path.startsWith(`${base}/`) ? path.slice(base.length + 1) : path;
}

function pickString(rec: Record<string, unknown>, keys: string[]): string | undefined {
  for (const k of keys) {
    const v = rec[k];
    if (typeof v === 'string') return v.replace(/\r\n/g, '\n');
  }
  return undefined;
}

function pathOf(input: unknown): string | undefined {
  if (!input || typeof input !== 'object') return undefined;
  return pickString(input as Record<string, unknown>, [
    'file_path',
    'path',
    'target_file',
    'notebook_path',
  ]);
}

/** The argument a tool call shows: its file, command, pattern or query. */
export function toolArgOf(input: unknown, cwd?: string): string {
  return toolArg(input, cwd);
}

function toolArg(input: unknown, cwd: string | undefined): string {
  if (!input || typeof input !== 'object') return '';
  const rec = input as Record<string, unknown>;
  const path = pathOf(input);
  if (path) return relativePath(path, cwd);
  for (const k of [
    'command',
    'pattern',
    'query',
    'url',
    'description',
    'prompt',
    'skill',
    'owner',
  ]) {
    const v = rec[k];
    if (typeof v === 'string' && v.trim()) return firstLine(v, 120);
  }
  const s = JSON.stringify(input);
  return s.length > 120 ? `${s.slice(0, 120)}…` : s;
}

/** The diff an edit call makes, from its input. */
export function editDiff(
  input: unknown,
): { added: number; removed: number; rows: DiffRow[]; more: number } | null {
  if (!input || typeof input !== 'object') return null;
  const rec = input as Record<string, unknown>;
  if (Array.isArray(rec.edits)) {
    const parts = (rec.edits as unknown[])
      .filter((e): e is Record<string, unknown> => !!e && typeof e === 'object')
      .map((e) =>
        lineDiff(pickString(e, ['old_string']) ?? '', pickString(e, ['new_string']) ?? ''),
      );
    if (parts.length === 0) return null;
    return {
      added: parts.reduce((n, p) => n + p.added, 0),
      removed: parts.reduce((n, p) => n + p.removed, 0),
      rows: parts.flatMap((p) => p.rows),
      more: parts.reduce((n, p) => n + p.more, 0),
    };
  }
  const next = pickString(rec, ['new_string', 'new_str', 'contents', 'content']);
  const prev = pickString(rec, ['old_string', 'old_str']) ?? '';
  if (next === undefined && !prev) return null;
  return lineDiff(prev, next ?? '');
}

type Context = {
  cwd: string | undefined;
  open: (ToolRow | EditRow)[];
  rows: Row[];
  /** The command the turn's prompt ran. */
  command?: string | undefined;
  /** The boundary the line before `/compact` wrote: it belongs next to the command's output. */
  claimed?: BoundaryRow | undefined;
  /** The boundary a block of the entry in hand just produced. */
  fresh?: BoundaryRow | undefined;
};

function attachResult(
  ctx: Context,
  key: string,
  lineNo: number,
  id: string | null,
  text: string,
  failed: boolean,
  ts: string | undefined,
  elided?: Elided,
): boolean {
  const index = id === null ? 0 : ctx.open.findIndex((r) => r.key.endsWith(`#${id}`));
  const target = ctx.open[index];
  if (!target || index < 0) return false;
  ctx.open.splice(index, 1);
  target.result = {
    key,
    lineNo,
    ...(ts ? { ts } : {}),
    text,
    failed,
    bytes: elided ? elided.bytes : text.length,
    ...(elided ? { elided } : {}),
  };
  return true;
}

function rowsOfBlock(
  ctx: Context,
  entry: Entry,
  raw: ElidedBlock | FullBlock,
  index: number,
): void {
  const { lineNo } = entry;
  const key = `${lineNo}-b${index}`;
  if ('elided' in raw) {
    const elided = elidedOf(entry, raw, index);
    switch (raw.type) {
      case 'text':
        if (entry.role === 'assistant')
          ctx.rows.push({ kind: 'text', key, lineNo, text: raw.preview, elided });
        else
          ctx.rows.push({
            kind: 'note',
            key,
            lineNo,
            family: 'system',
            label: 'system',
            text: raw.preview,
            elided,
          });
        return;
      case 'thinking':
        ctx.rows.push({ kind: 'thinking', key, lineNo, text: raw.preview, elided });
        return;
      case 'tool-result':
        if (!attachResult(ctx, key, lineNo, null, raw.preview, false, entry.ts, elided)) {
          ctx.rows.push({
            kind: 'note',
            key,
            lineNo,
            family: 'result',
            label: 'result',
            text: raw.preview,
            elided,
          });
        }
        return;
      default:
        ctx.rows.push({
          kind: 'note',
          key,
          lineNo,
          family: 'other',
          label: raw.type,
          text: raw.preview,
          elided,
        });
        return;
    }
  }
  switch (raw.type) {
    case 'text':
      if (entry.role === 'assistant') ctx.rows.push({ kind: 'text', key, lineNo, text: raw.text });
      else if (STDOUT.test(raw.text)) {
        const out = stripAnsi(STDOUT.exec(raw.text)?.[1] ?? '').trim();
        if (out === '') return;
        const row: CommandRow = { kind: 'command', key, lineNo, text: out };
        if (ctx.command) row.command = ctx.command;
        ctx.rows.push(row);
        if (ctx.command === 'compact') {
          row.compact = ctx.claimed?.sizes ? { ...ctx.claimed.sizes } : {};
          if (ctx.claimed) {
            delete ctx.claimed.sizes;
            ctx.rows.push(ctx.claimed);
            ctx.claimed = undefined;
          }
        }
      } else if (COMMAND_TAGS.test(raw.text)) return;
      else
        ctx.rows.push({
          kind: 'note',
          key,
          lineNo,
          family: 'system',
          label: 'system',
          text: raw.text,
        });
      return;
    case 'thinking':
      ctx.rows.push({ kind: 'thinking', key, lineNo, text: raw.text });
      return;
    case 'tool-call': {
      const callKey = `${key}#${raw.id}`;
      const path = pathOf(raw.input);
      if (raw.kind === 'edit' && path) {
        const diff = editDiff(raw.input);
        if (diff) {
          const row: EditRow = {
            kind: 'edit',
            key: callKey,
            lineNo,
            tool: raw.name,
            toolKind: raw.kind,
            ...(raw.id ? { toolUseId: raw.id } : {}),
            path: relativePath(path, ctx.cwd),
            language: languageOfPath(path),
            ...diff,
          };
          ctx.rows.push(row);
          ctx.open.push(row);
          return;
        }
      }
      const row: ToolRow = {
        kind: 'tool',
        key: callKey,
        lineNo,
        tool: raw.name,
        toolKind: raw.kind,
        ...(raw.id ? { toolUseId: raw.id } : {}),
        ...(raw.mcp ? { mcp: raw.mcp } : {}),
        ...(entry.ts ? { ts: entry.ts } : {}),
        arg: toolArg(raw.input, ctx.cwd),
        input: raw.input ?? {},
        ...(path ? { path: relativePath(path, ctx.cwd) } : {}),
      };
      ctx.rows.push(row);
      ctx.open.push(row);
      return;
    }
    case 'tool-result':
      if (!attachResult(ctx, key, lineNo, raw.id, raw.content, raw.isError === true, entry.ts)) {
        ctx.rows.push({
          kind: 'note',
          key,
          lineNo,
          family: 'result',
          label: 'result',
          text: raw.content,
          failed: raw.isError === true,
        });
      }
      return;
    case 'image':
      ctx.rows.push({
        kind: 'tool',
        key,
        lineNo,
        tool: 'image',
        toolKind: 'view',
        arg: imageName(raw),
        input: raw.url ?? raw.mediaType,
        ...(raw.data
          ? { result: { key, lineNo, text: '', failed: false, bytes: base64Bytes(raw.data) } }
          : {}),
      });
      return;
    case 'other':
      if (raw.kind === 'compact_boundary') {
        const { text, sizes } = parseBoundary(raw);
        const row: BoundaryRow = {
          kind: 'boundary',
          key,
          lineNo,
          text,
          ...(sizes ? { sizes } : {}),
        };
        ctx.rows.push(row);
        ctx.fresh = row;
        return;
      }
      ctx.rows.push({
        kind: 'note',
        key,
        lineNo,
        family: raw.kind === 'attachment' ? 'file' : 'other',
        label: raw.kind,
        text: raw.label ?? raw.text ?? '',
      });
      return;
  }
}

/** A user line that starts a turn: it has text that is the user's own. */
function promptOf(
  entry: Entry,
): { text: string; elided?: Elided; command?: CommandCall; index: number } | null {
  if (entry.role !== 'user') return null;
  for (const [i, block] of entry.blocks.entries()) {
    if ('elided' in block) {
      if (block.type === 'text' && !META_TEXT.test(block.preview)) {
        return { text: block.preview, elided: elidedOf(entry, block, i), index: i };
      }
    } else if (block.type === 'text' && block.text.trim() !== '') {
      const command = parseCommand(block.text);
      if (command && /^\s*(<command-name>|\/)/.test(block.text)) {
        const text = `/${command.name}${command.args ? ` ${command.args}` : ''}`;
        return { text, command, index: i };
      }
      if (!META_TEXT.test(block.text)) return { text: block.text.trim(), index: i };
    }
  }
  return null;
}

/** Rows that rest closed: a failed result and an elided block show their output, so they stay on their own. */
function isFoldable(row: Row): row is ToolRow {
  return row.kind === 'tool' && !row.result?.elided && !row.result?.failed;
}

/** Three or more consecutive tool rows without an open well fold into one row naming their verbs. */
export const FOLD_MIN = 3;

export function foldTools(rows: Row[]): Row[] {
  const out: Row[] = [];
  let run: ToolRow[] = [];
  const flush = () => {
    if (run.length >= FOLD_MIN) {
      const first = run[0] as ToolRow;
      out.push({ kind: 'fold', key: `fold-${first.key}`, lineNo: first.lineNo, tools: run });
    } else out.push(...run);
    run = [];
  };
  for (const row of rows) {
    if (isFoldable(row)) run.push(row);
    else {
      flush();
      out.push(row);
    }
  }
  flush();
  return out;
}

/** The turn's counts: the files it changed (edited or written), its tool calls and its duration. */
function summarize(rows: Row[], first: string | undefined, last: string | undefined): TurnSummary {
  const files = new Set<string>();
  let tools = 0;
  for (const row of rows) {
    if (row.kind === 'edit') {
      tools++;
      files.add(row.path);
    } else if (row.kind === 'tool') {
      tools++;
      if (row.path && row.toolKind === 'write') files.add(row.path);
    }
  }
  const a = first ? Date.parse(first) : Number.NaN;
  const b = last ? Date.parse(last) : Number.NaN;
  const span = b - a;
  return {
    files: files.size,
    tools,
    durationMs: Number.isFinite(span) && span >= 1000 ? span : null,
  };
}

type Draft = { turn: Turn; ctx: Context; firstTs: string | undefined; lastTs: string | undefined };

export function buildTurns(entries: readonly Entry[], opts: { cwd?: string } = {}): Turn[] {
  const drafts: Draft[] = [];
  let current: Draft | null = null;
  // The boundary of the latest entry, while nothing else has followed it: `/compact` writes it before its own lines.
  let pending: { draft: Draft; row: BoundaryRow } | null = null;
  const begin = (entry: Entry, prompt: Turn['prompt']): Draft => {
    const turn: Turn = {
      key: `${prompt ? 't' : 'h'}${entry.lineNo}`,
      startLine: entry.lineNo,
      endLine: entry.lineNo,
      prompt,
      ts: entry.ts,
      rows: [],
      summary: { files: 0, tools: 0, durationMs: null },
    };
    const draft: Draft = {
      turn,
      ctx: { cwd: opts.cwd, open: [], rows: turn.rows },
      firstTs: entry.ts,
      lastTs: entry.ts,
    };
    drafts.push(draft);
    return draft;
  };
  for (const entry of entries) {
    // A steered message belongs to the turn it landed in; it opens no turn of its own.
    const prompt = entry.steered && current ? null : promptOf(entry);
    if (prompt) {
      const claimed = prompt.command?.name === 'compact' ? pending?.row : undefined;
      if (claimed && pending) {
        const { draft } = pending;
        draft.ctx.rows.splice(draft.ctx.rows.indexOf(claimed), 1);
        if (draft.turn.prompt === null && draft.ctx.rows.length === 0) {
          drafts.splice(drafts.indexOf(draft), 1);
        }
      }
      current = begin(entry, {
        text: prompt.text,
        ...(prompt.elided ? { elided: prompt.elided } : {}),
        ...(prompt.command ? { command: prompt.command } : {}),
      });
      current.ctx.command = prompt.command?.name;
      current.ctx.claimed = claimed;
    } else {
      current ??= begin(entry, null);
    }
    current.turn.endLine = entry.lineNo;
    if (entry.ts) current.lastTs = entry.ts;
    entry.blocks.forEach((block, i) => {
      if (prompt && i === prompt.index) return;
      if (!current) return;
      if (entry.steered && block.type === 'text') {
        const key = `${entry.lineNo}-b${i}`;
        if ('elided' in block) {
          current.ctx.rows.push({
            kind: 'steer',
            key,
            lineNo: entry.lineNo,
            text: block.preview,
            elided: elidedOf(entry, block, i),
          });
        } else if (block.text.trim() !== '') {
          current.ctx.rows.push({
            kind: 'steer',
            key,
            lineNo: entry.lineNo,
            text: block.text.trim(),
          });
        }
        return;
      }
      rowsOfBlock(current.ctx, entry, block, i);
    });
    const fresh: BoundaryRow | undefined = current.ctx.fresh;
    current.ctx.fresh = undefined;
    pending = fresh ? { draft: current, row: fresh } : null;
  }
  return drafts.map(({ turn, ctx, firstTs, lastTs }) => {
    // A boundary whose command printed nothing still marks the compaction.
    if (ctx.claimed) turn.rows.push(ctx.claimed);
    turn.rows = foldTools(turn.rows);
    turn.summary = summarize(
      turn.rows.flatMap((r) => (r.kind === 'fold' ? r.tools : [r])),
      firstTs,
      lastTs,
    );
    return turn;
  });
}
