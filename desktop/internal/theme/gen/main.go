// Command gen writes the theme package's Go from the design system's
// tokens.json and layout.json, the one source the canvas's tokens.css and
// layout.css are compiled from too. Run it with go generate in the theme
// package; never edit what it writes.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"strconv"
	"strings"
)

type token struct {
	Name  string          `json:"name"`
	Value json.RawMessage `json:"value"`
	MyGO  string          `json:"mygo"`
}

type family struct {
	Tokens []token `json:"tokens"`
}

type style struct {
	Name          string `json:"name"`
	Family        string `json:"family"`
	FontSize      string `json:"fontSize"`
	LineHeight    string `json:"lineHeight"`
	FontWeight    int    `json:"fontWeight"`
	LetterSpacing string `json:"letterSpacing"`
}

type tokens struct {
	Color struct {
		Tokens []token `json:"tokens"`
	} `json:"color"`
	Type struct {
		Groups []struct {
			Family string  `json:"family"`
			Styles []style `json:"styles"`
		} `json:"groups"`
	} `json:"type"`
	Spacing family `json:"spacing"`
	Radius  family `json:"radius"`
	Shadow  family `json:"shadow"`
	Size    family `json:"size"`
	Line    family `json:"line"`
	Motion  family `json:"motion"`
}

type pattern struct {
	Name       string   `json:"name"`
	Direction  string   `json:"direction"`
	Gap        string   `json:"gap"`
	Align      string   `json:"align"`
	Justify    string   `json:"justify"`
	Width      string   `json:"width"`
	Height     []string `json:"height"`
	Padding    []string `json:"padding"`
	MaxWidth   []string `json:"max-width"`
	Indent     []string `json:"indent"`
	Wrap       bool     `json:"wrap"`
	CenterSelf bool     `json:"center-self"`
	Grow       float64  `json:"grow"`
}

func main() {
	var t tokens
	tokensJSON, err := os.ReadFile("tokens.json")
	if err != nil {
		log.Fatal(err)
	}
	decode("tokens.json", tokensJSON, &t)
	var l struct {
		Patterns []pattern `json:"patterns"`
	}
	layoutJSON, err := os.ReadFile("layout.json")
	if err != nil {
		log.Fatal(err)
	}
	decode("layout.json", layoutJSON, &l)
	sizes := map[string]float64{}
	for _, f := range []family{t.Spacing, t.Radius, t.Size, t.Line} {
		for _, tk := range f.Tokens {
			sizes[tk.Name] = px(str(tk.Value))
		}
	}
	write("tokens_gen.go", genTokens(t))
	write("layout_gen.go", genLayout(l.Patterns, sizes))
}

func decode(path string, data []byte, v any) {
	if err := json.Unmarshal(data, v); err != nil {
		log.Fatalf("%s: %v", path, err)
	}
}

func write(path string, src []byte) {
	out, err := format.Source(src)
	if err != nil {
		log.Fatalf("%s: %v\n%s", path, err, src)
	}
	if err := os.WriteFile(path, out, 0o600); err != nil {
		log.Fatal(err)
	}
}

const header = "// Code generated by go run ./gen from tokens.json and layout.json; DO NOT EDIT.\n\npackage theme\n\n"

// goName turns a token name into a Go name: space-1_5 is Space1Half,
// titlebar is TitleBar, ui-medium is UIMedium.
func goName(name string) string {
	words := map[string]string{"ui": "UI", "xs": "XS", "titlebar": "TitleBar", "0_5": "Half", "1_5": "1Half"}
	var b strings.Builder
	for _, p := range strings.Split(name, "-") {
		if w, ok := words[p]; ok {
			b.WriteString(w)
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func str(raw json.RawMessage) string {
	var s string
	if json.Unmarshal(raw, &s) == nil {
		return s
	}
	return ""
}

func themed(raw json.RawMessage) (dark, light string) {
	var m map[string]string
	if json.Unmarshal(raw, &m) == nil {
		return m["dark"], m["light"]
	}
	s := str(raw)
	return s, s
}

func px(s string) float64 {
	v, err := strconv.ParseFloat(strings.TrimSuffix(strings.TrimSpace(s), "px"), 64)
	if err != nil {
		log.Fatalf("not a length: %q", s)
	}
	return v
}

func num(v float64) string { return strconv.FormatFloat(v, 'f', -1, 64) }

var (
	hexColor  = regexp.MustCompile(`^#[0-9a-fA-F]{6}$`)
	rgbaColor = regexp.MustCompile(`^rgba\(([^)]*)\)$`)
	timing    = regexp.MustCompile(`^(\d+)ms(?: (.*))?$`)
	bezier    = regexp.MustCompile(`^cubic-bezier\(([^)]*)\)$`)
)

// color is the Go expression of a CSS color, or "" when s is not a plain
// color (a gradient is the canvas's alone).
func color(s string) string {
	s = strings.TrimSpace(s)
	if hexColor.MatchString(s) {
		return fmt.Sprintf("ui.Hex(%q)", strings.ToUpper(s))
	}
	if m := rgbaColor.FindStringSubmatch(s); m != nil {
		return "ui.RGBA(" + strings.ReplaceAll(m[1], ",", ", ") + ")"
	}
	return ""
}

// shadow is the Go expression of a CSS box shadow: x y blur [spread] color.
func shadow(s string) string {
	i := strings.Index(s, "rgba(")
	if i < 0 {
		log.Fatalf("shadow without a color: %q", s)
	}
	parts := strings.Fields(s[:i])
	v := []string{"0", "0", "0", "0"}
	for j, p := range parts {
		v[j] = num(px(p))
	}
	return fmt.Sprintf("Shadow{X: %s, Y: %s, Blur: %s, Spread: %s, Color: %s}", v[0], v[1], v[2], v[3], color(s[i:]))
}

func genTokens(t tokens) []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("import (\n\t\"time\"\n\n\t\"github.com/egoist/mygo/ui\"\n)\n\n")

	type field struct{ name, kind, dark, light string }
	var fields []field
	for _, tk := range t.Color.Tokens {
		d, l := themed(tk.Value)
		if color(d) == "" || color(l) == "" {
			continue
		}
		fields = append(fields, field{goName(tk.Name), "ui.Color", color(d), color(l)})
	}
	for _, tk := range t.Shadow.Tokens {
		d, l := themed(tk.Value)
		fields = append(fields, field{goName(tk.Name), "Shadow", shadow(d), shadow(l)})
	}
	b.WriteString("// Colors are the colors and shadows of one appearance, named as in the\n// design system's tokens.json.\ntype Colors struct {\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "\t%s %s\n", f.name, f.kind)
	}
	b.WriteString("}\n\n// For returns the colors of the dark or the light appearance.\nfunc For(dark bool) Colors {\n\tif dark {\n\t\treturn Colors{\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "\t\t\t%s: %s,\n", f.name, f.dark)
	}
	b.WriteString("\t\t}\n\t}\n\treturn Colors{\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "\t\t%s: %s,\n", f.name, f.light)
	}
	b.WriteString("\t}\n}\n\n")

	for _, f := range []struct {
		doc string
		fam family
	}{
		{"Spacing, in points: gaps and padding take only these.", t.Spacing},
		{"Radii, in points.", t.Radius},
		{"Line widths, in points.", t.Line},
		{"Fixed sizes, in points.", t.Size},
	} {
		fmt.Fprintf(&b, "// %s\nconst (\n", f.doc)
		for _, tk := range f.fam.Tokens {
			fmt.Fprintf(&b, "\t%s = %s\n", goName(tk.Name), num(px(str(tk.Value))))
		}
		b.WriteString(")\n\n")
	}

	b.WriteString("// Motion: animations, durations, distances and scales.\nvar (\n")
	for _, tk := range t.Motion.Tokens {
		name, v := goName(tk.Name), str(tk.Value)
		switch m := timing.FindStringSubmatch(v); {
		case tk.MyGO != "":
			fmt.Fprintf(&b, "\t%s = %s\n", name, tk.MyGO)
		case m != nil && m[2] == "":
			fmt.Fprintf(&b, "\t%s = %s * time.Millisecond\n", name, m[1])
		case m != nil && m[2] == "linear":
			fmt.Fprintf(&b, "\t%s = ui.Animation{Duration: %s * time.Millisecond, Ease: ui.Linear}\n", name, m[1])
		case m != nil:
			c := bezier.FindStringSubmatch(m[2])
			if c == nil {
				log.Fatalf("%s: unknown easing %q", tk.Name, m[2])
			}
			fmt.Fprintf(&b, "\t%s = ui.Animation{Duration: %s * time.Millisecond, Ease: ui.CubicBezier(%s)}\n", name, m[1], c[1])
		case strings.HasSuffix(v, "px"):
			fmt.Fprintf(&b, "\t%s float32 = %s\n", name, num(px(v)))
		default:
			f, err := strconv.ParseFloat(v, 64)
			if err != nil {
				log.Fatalf("%s: unknown value %q", tk.Name, v)
			}
			fmt.Fprintf(&b, "\t%s float32 = %s\n", name, num(f))
		}
	}
	b.WriteString(")\n\n")

	var styles []style
	for _, g := range t.Type.Groups {
		for _, s := range g.Styles {
			if s.Family == "" {
				s.Family = g.Family
			}
			styles = append(styles, s)
		}
	}
	b.WriteString("// The text styles: only these sizes and the weights 400, 500 and 600.\nconst (\n")
	for i, s := range styles {
		if i == 0 {
			fmt.Fprintf(&b, "\t%s Style = iota\n", goName(s.Name))
		} else {
			fmt.Fprintf(&b, "\t%s\n", goName(s.Name))
		}
	}
	b.WriteString(")\n\nvar styles = [...]styleSpec{\n")
	for _, s := range styles {
		size := px(s.FontSize)
		spacing := 0.0
		if s.LetterSpacing != "" {
			em, err := strconv.ParseFloat(strings.TrimSuffix(s.LetterSpacing, "em"), 64)
			if err != nil {
				log.Fatalf("%s: letter spacing %q", s.Name, s.LetterSpacing)
			}
			spacing = em * size
		}
		fmt.Fprintf(&b, "\t%s: {size: %s, line: %s, weight: %d, spacing: %s, mono: %v},\n",
			goName(s.Name), num(size), num(px(s.LineHeight)), s.FontWeight, num(spacing), s.Family == "mono")
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func genLayout(ps []pattern, sizes map[string]float64) []byte {
	val := func(name string) string {
		if name == "0" {
			return "0"
		}
		if _, ok := sizes[name]; !ok {
			log.Fatalf("layout.json: unknown token %q", name)
		}
		return goName(name)
	}
	align := map[string]string{"": "", "center": "ui.Center", "stretch": "ui.Stretch", "start": "ui.Start", "end": "ui.End"}
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("import \"github.com/egoist/mygo/ui\"\n\n// The layouts of layout.json: every assembly uses one of them.\nvar (\n")
	for _, p := range ps {
		var f []string
		if p.Direction == "column" {
			f = append(f, "Column: true")
		}
		if p.Gap != "" {
			f = append(f, "Gap: "+val(p.Gap))
		}
		if a := align[p.Align]; a != "" {
			f = append(f, "Align: "+a, "AlignSet: true")
		}
		if a := align[p.Justify]; a != "" {
			f = append(f, "Justify: "+a, "JustifySet: true")
		}
		if p.Width == "fill" {
			f = append(f, "Fill: true")
		}
		if p.Wrap {
			f = append(f, "Wrap: true")
		}
		if len(p.Height) > 0 {
			f = append(f, "Height: "+val(p.Height[0]))
		}
		if len(p.MaxWidth) > 0 {
			f = append(f, "MaxWidth: "+val(p.MaxWidth[0]))
		}
		if p.CenterSelf {
			f = append(f, "CenterSelf: true")
		}
		if p.Grow > 0 {
			f = append(f, "Grow: "+num(p.Grow))
		}
		if len(p.Padding) > 0 {
			var v []string
			for _, x := range p.Padding {
				v = append(v, val(x))
			}
			f = append(f, "Padding: []float32{"+strings.Join(v, ", ")+"}")
		}
		if len(p.Indent) > 0 {
			var v []string
			for _, x := range p.Indent {
				v = append(v, val(x))
			}
			f = append(f, "Padding: []float32{0, 0, 0, "+strings.Join(v, " + ")+"}")
		}
		fmt.Fprintf(&b, "\t%s = Layout{%s}\n", goName(p.Name), strings.Join(f, ", "))
	}
	b.WriteString(")\n")
	return b.Bytes()
}
