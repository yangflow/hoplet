package main

import (
	"fmt"
	"go/ast"
	"slices"
	"strings"
	"unicode"
)

var builtinTypes = map[string]string{
	"string": "String",
	"bool":   "Bool",
	"int":    "Int",
	"int64":  "Int64",
	"uint16": "UInt16",
	"uint32": "UInt32",
	"uint64": "UInt64",
}

// swiftType maps a Go field type to Swift. known holds the generated names.
func swiftType(e ast.Expr, known map[string]bool) (string, error) {
	switch t := e.(type) {
	case *ast.Ident:
		if s, ok := builtinTypes[t.Name]; ok {
			return s, nil
		}
		if known[t.Name] {
			return t.Name, nil
		}
		return "", fmt.Errorf("unsupported type %s", t.Name)
	case *ast.SelectorExpr:
		pkg, ok := t.X.(*ast.Ident)
		if ok && pkg.Name == "time" && t.Sel.Name == "Time" {
			return "Date", nil
		}
		if ok && pkg.Name == "json" && t.Sel.Name == "RawMessage" {
			return "JSONValue", nil
		}
		return "", fmt.Errorf("unsupported type %s.%s", pkg.Name, t.Sel.Name)
	case *ast.ArrayType:
		if t.Len != nil {
			return "", fmt.Errorf("arrays of fixed length are not supported")
		}
		if id, ok := t.Elt.(*ast.Ident); ok && id.Name == "byte" {
			return "Data", nil
		}
		elem, err := swiftType(t.Elt, known)
		if err != nil {
			return "", err
		}
		return "[" + elem + "]", nil
	case *ast.StarExpr:
		if _, nested := t.X.(*ast.StarExpr); nested {
			return "", fmt.Errorf("pointers to pointers are not supported")
		}
		elem, err := swiftType(t.X, known)
		if err != nil {
			return "", err
		}
		return elem + "?", nil
	default:
		return "", fmt.Errorf("unsupported type expression %T", e)
	}
}

var swiftKeywords = map[string]bool{
	"as": true, "associatedtype": true, "break": true, "case": true, "catch": true,
	"class": true, "continue": true, "default": true, "defer": true, "deinit": true,
	"do": true, "else": true, "enum": true, "extension": true, "fallthrough": true,
	"false": true, "fileprivate": true, "for": true, "func": true, "guard": true,
	"if": true, "import": true, "in": true, "init": true, "inout": true,
	"internal": true, "is": true, "let": true, "nil": true, "operator": true,
	"private": true, "precedencegroup": true, "protocol": true, "public": true,
	"repeat": true, "rethrows": true, "return": true, "self": true, "static": true,
	"struct": true, "subscript": true, "super": true, "switch": true, "throw": true,
	"throws": true, "true": true, "try": true, "typealias": true, "var": true,
	"where": true, "while": true,
}

func quoteIdent(s string) string {
	if swiftKeywords[s] {
		return "`" + s + "`"
	}
	return s
}

// camelCase joins the alphanumeric runs of s into lowerCamelCase, keeping
// capitals already inside a run.
func camelCase(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	})
	var b strings.Builder
	for i, part := range parts {
		runes := []rune(part)
		if i == 0 {
			runes[0] = unicode.ToLower(runes[0])
		} else {
			runes[0] = unicode.ToUpper(runes[0])
		}
		b.WriteString(string(runes))
	}
	return b.String()
}

// caseName is the Swift enum case for a constant's value.
func caseName(value string) string {
	if value == "" {
		return "empty"
	}
	name := camelCase(value)
	if name == "" || unicode.IsDigit([]rune(name)[0]) {
		return "v" + name
	}
	return name
}

func lowerFirst(s string) string {
	runes := []rune(s)
	runes[0] = unicode.ToLower(runes[0])
	return string(runes)
}

type writer struct{ strings.Builder }

func (w *writer) line(format string, args ...any) {
	fmt.Fprintf(&w.Builder, format+"\n", args...)
}

// emit renders the whole Swift file.
func emit(m *model) ([]byte, error) {
	known := map[string]bool{}
	for _, s := range m.structs {
		known[s.name] = true
	}
	for _, s := range m.strs {
		known[s.name] = true
	}

	w := &writer{}
	w.line("// Code generated by tools/swiftgen. DO NOT EDIT.")
	w.line("")
	w.line("import Foundation")
	for _, s := range m.strs {
		if err := emitString(w, s); err != nil {
			return nil, err
		}
	}
	for _, s := range m.structs {
		if err := emitStruct(w, s, known); err != nil {
			return nil, err
		}
	}
	if err := emitEvents(w, m.events); err != nil {
		return nil, err
	}
	return []byte(w.String()), nil
}

func emitString(w *writer, s stringDecl) error {
	w.line("")
	if len(s.values) == 0 {
		w.line("public struct %s: RawRepresentable, Codable, Hashable, Sendable, ProtoZero {", s.name)
		w.line("  public var rawValue: String")
		w.line("  public init(rawValue: String) { self.rawValue = rawValue }")
		w.line("  public static var protoZero: Self { Self(rawValue: \"\") }")
		w.line("  public var isProtoZero: Bool { rawValue.isEmpty }")
		w.line("}")
		return nil
	}

	seen := map[string]string{"unknown": "the fallback case"}
	for _, v := range s.values {
		name := caseName(v)
		if other, dup := seen[name]; dup {
			return fmt.Errorf("%s: value %q maps to case %s, which is taken by %s", s.name, v, name, other)
		}
		seen[name] = fmt.Sprintf("value %q", v)
	}

	w.line("public enum %s: RawRepresentable, Codable, Hashable, Sendable, ProtoZero {", s.name)
	for _, v := range s.values {
		w.line("  case %s", quoteIdent(caseName(v)))
	}
	w.line("  case unknown(String)")
	w.line("")
	w.line("  public init(rawValue: String) {")
	w.line("    switch rawValue {")
	for _, v := range s.values {
		w.line("    case %q: self = .%s", v, quoteIdent(caseName(v)))
	}
	w.line("    default: self = .unknown(rawValue)")
	w.line("    }")
	w.line("  }")
	w.line("")
	w.line("  public var rawValue: String {")
	w.line("    switch self {")
	for _, v := range s.values {
		w.line("    case .%s: return %q", quoteIdent(caseName(v)), v)
	}
	w.line("    case .unknown(let value): return value")
	w.line("    }")
	w.line("  }")
	w.line("")
	w.line("  public static var protoZero: Self { Self(rawValue: \"\") }")
	w.line("  public var isProtoZero: Bool { rawValue.isEmpty }")
	w.line("}")
	return nil
}

func emitStruct(w *writer, s structDecl, known map[string]bool) error {
	w.line("")
	w.line("public struct %s: Codable, Hashable, Sendable, ProtoZero {", s.name)
	if len(s.fields) == 0 {
		w.line("  public init() {}")
		w.line("  public static var protoZero: Self { Self() }")
		w.line("  public var isProtoZero: Bool { false }")
		w.line("}")
		return nil
	}

	type field struct {
		name, typ, json string
		optional, omit  bool
	}
	fields := make([]field, 0, len(s.fields))
	seen := map[string]bool{}
	for _, f := range s.fields {
		typ, err := swiftType(f.typ, known)
		if err != nil {
			return fmt.Errorf("%s.%s: %w", s.name, f.jsonName, err)
		}
		name := quoteIdent(camelCase(f.jsonName))
		if seen[name] {
			return fmt.Errorf("%s: two fields map to %s", s.name, name)
		}
		seen[name] = true
		fields = append(fields, field{name: name, typ: typ, json: f.jsonName, optional: strings.HasSuffix(typ, "?"), omit: f.omitEmpty})
	}

	for _, f := range fields {
		w.line("  public var %s: %s", f.name, f.typ)
	}
	w.line("")
	w.line("  public init(")
	for i, f := range fields {
		def := ".protoZero"
		if f.optional {
			def = "nil"
		}
		sep := ","
		if i == len(fields)-1 {
			sep = ""
		}
		w.line("    %s: %s = %s%s", f.name, f.typ, def, sep)
	}
	w.line("  ) {")
	for _, f := range fields {
		w.line("    self.%s = %s", f.name, f.name)
	}
	w.line("  }")
	w.line("")
	w.line("  private enum CodingKeys: String, CodingKey {")
	for _, f := range fields {
		w.line("    case %s = %q", f.name, f.json)
	}
	w.line("  }")
	w.line("")
	w.line("  public init(from decoder: any Decoder) throws {")
	w.line("    let c = try decoder.container(keyedBy: CodingKeys.self)")
	for _, f := range fields {
		if f.optional {
			w.line("    %s = try c.decodeIfPresent(%s.self, forKey: .%s)", f.name, strings.TrimSuffix(f.typ, "?"), f.name)
		} else {
			w.line("    %s = try c.decodeOrZero(%s.self, forKey: .%s)", f.name, f.typ, f.name)
		}
	}
	w.line("  }")
	w.line("")
	w.line("  public func encode(to encoder: any Encoder) throws {")
	w.line("    var c = encoder.container(keyedBy: CodingKeys.self)")
	for _, f := range fields {
		switch {
		case f.optional && f.omit:
			w.line("    try c.encodeIfPresent(%s, forKey: .%s)", f.name, f.name)
		case f.omit:
			w.line("    try c.encodeUnlessZero(%s, forKey: .%s)", f.name, f.name)
		default:
			w.line("    try c.encode(%s, forKey: .%s)", f.name, f.name)
		}
	}
	w.line("  }")
	w.line("")
	w.line("  public static var protoZero: Self { Self() }")
	w.line("  public var isProtoZero: Bool { false }")
	w.line("}")
	return nil
}

func emitEvents(w *writer, events []eventDecl) error {
	seen := map[string]bool{}
	for _, e := range events {
		key := fmt.Sprintf("%s/%d", e.eventType, e.version)
		if seen[key] {
			return fmt.Errorf("two payloads for event %s", key)
		}
		seen[key] = true
	}
	ordered := slices.Clone(events)

	w.line("")
	w.line("/// An event's payload. Types and versions this build does not know decode to")
	w.line("/// `unknown`, because a daemon can be newer than the app.")
	w.line("public enum EventPayload: Hashable, Sendable {")
	for _, e := range ordered {
		w.line("  case %s(%s)", quoteIdent(lowerFirst(e.payload)), e.payload)
	}
	w.line("  case unknown(type: EventType, v: UInt16)")
	w.line("}")
	w.line("")
	w.line("extension Event {")
	w.line("  /// Decodes `payload` according to `type` and `v`.")
	w.line("  public func decodedPayload() throws -> EventPayload {")
	w.line("    switch (type.rawValue, v) {")
	for _, e := range ordered {
		w.line("    case (%q, %d): return .%s(try payload.decode(%s.self))", e.eventType, e.version, quoteIdent(lowerFirst(e.payload)), e.payload)
	}
	w.line("    default: return .unknown(type: type, v: v)")
	w.line("    }")
	w.line("  }")
	w.line("}")
	return nil
}
